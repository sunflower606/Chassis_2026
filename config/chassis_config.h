#ifndef CHASSIS_CONFIG_H
#define CHASSIS_CONFIG_H

/* 电机/跟随的可调参数单独成册（DUTY_MAX、RAMP、FOLLOW_* 等）。
 * 在这里 include，其它 .c 文件照旧只写 #include "chassis_config.h" 即可。 */
#include "motor_pid_config.h"

/* ============================================================================
 * 循迹主控板（Chassis_2026）控制参数
 *
 * ⚠️ 本文件里的阈值全部是**占位值**，必须实测后重新标定。
 *    每个参数后面标注了标定方法，标定完把「待标定」改成实测日期。
 *
 * 对应需求：《实验室学习项目》
 *   模式 1【循迹 + 云台人体跟踪】：小车沿黑线行驶，云台独立跟踪人
 *   模式 2【纯人体跟随】：无黑线约束，整车跟随人体目标
 * ========================================================================== */

/* ------------------------------------------------------------- 任务节拍
 * 循迹需要比云台更快：红外对管响应快、黑线细，10 ms 太慢容易冲出去。
 * 5 ms（200 Hz）是常见取值。
 * ------------------------------------------------------------------------- */
#define CHASSIS_CONTROL_PERIOD_MS           5U
#define CHASSIS_CONTROL_DT_S                0.005f

#define CHASSIS_DISPLAY_PERIOD_MS           100U
/* VOFA+ 波形输出周期：20 ms = 50 帧/秒，肉眼看着流畅，串口占用约 2.2 kB/s。
 * 想更细（看 5 ms 控制环的抖动）可改 10；只想看趋势可改 50。 */
/* ---------- 黑匣子（方案 B） ----------
 * 采样周期：100 ms 一条，RAM 存 300 条 = 30 秒，Flash 存 284 条 = 28.4 秒。
 * 为什么是 100 ms：Flash 只分了 5 KB，100 ms 是"看趋势"够用的最粗粒度；
 * 想看细节就同时开 wave=1（20 ms 波形输出），两者互不影响。 */
#define CHASSIS_BLACKBOX_PERIOD_MS  100U

#define CHASSIS_WAVE_PERIOD_MS    20U

#define CHASSIS_DEBUG_PERIOD_MS             1000U   /* 串口调试行周期（2026-11-16 由 500 调到 1000：
                                                   * 蓝牙看日志时 2 行/秒太快，来不及读。
                                                   * 调大 = 更慢更好读；调小 = 定位瞬态问题时信息更密。
                                                   * 注意：chassis_task.c 里 sw= 的统计窗口固定 1 秒，不受本值影响。 */

/* 按键消抖时间：电平稳定这么久才算一次有效动作 */
#define CHASSIS_KEY_DEBOUNCE_MS             20U

/* ------------------------------------------------------------- 循迹参数 */
/* 传感器极性：1 = 压黑线时输出低电平
 *           0 = 压黑线时输出高电平
 *
 * 2026-11-18 按参考工程（Keil5「工程模板 - 副本」System/linefollow.c 的
 * LINE_ACTIVE_LOW=0）改为 0：那块板的传感器是「白底灯亮→输出低、黑线灯灭→输出高」，
 * 所以压黑线读到的电平是 1。两边用的是同一组引脚（PA2/PA3/PA8/PA11/PA12/PA15/PB3），
 * 属同一块硬件。
 * 上电复核方法：把某个探头压在黑线上，OLED 第 2 行 Raw 位图里对应位应为 1。 */
#define CHASSIS_LINE_ACTIVE_LOW             0U

/* 丢线判定：连续多少次采样全部看不到黑线 -> 判为脱线
 * 参考工程是「一帧全白就立即停车」；这里保留 100 ms 防抖，
 * 因为 7 路全白在赛道接缝/急弯处会瞬时出现，立即停会让车一顿一停。
 * 想完全照搬参考工程就把本值改成 1U。 */
#define CHASSIS_LINE_LOST_COUNT             20U     /* 20 × 5 ms = 100 ms */

/* 循迹基础速度（千分比，0~1000）
 * 参考工程取 250，这里沿用；赛道跑不稳再降，出弯太慢再加。 */
#define CHASSIS_LINE_BASE_SPEED             250U

/* 循迹转向修正强度（千分比 / 每 1% 位置偏差）
 *
 * 与参考工程的等效换算：参考工程 `KP = 80`、偏差 `error = 加权平均(权重 -3..+3)`，
 * 即 `差速 = 80 × error`（error=±3 时 ±240‰）。
 * 本工程把位置归一化到 ±100（`position = error × 100 / 3`），
 * 所以要让差速相同必须取 `GAIN = 80 × 3 = 240`。
 * 调大发飘/画龙，调小弯道转不过来。 */
#define CHASSIS_LINE_STEER_GAIN             240

/* 循迹转向符号：+1 或 -1
 * 装车后若发现「线在右边、车却往左拐」，把这个改成 -1（只改这里，别改差速合成）。 */
#define CHASSIS_LINE_STEER_SIGN             (+1)

/* 循迹差速上限（千分比）
 * 规范要求输出必须限幅；正常赛道不会用满，留作弯道保护，
 * 避免 position 抖动时把一轮瞬间拉到与基础速度等幅而打滑。 */
#define CHASSIS_LINE_STEER_MAX              250

/* 弯道降速：|position| 越大（弯越急）速度越低。
 * 0   = 不降速（老行为）
 * 50  = 满偏转时只剩 50% 速度（推荐起点）
 * 80  = 弯里几乎停住，只在直道冲 —— 容易在弯里被后车顶到
 * 单位：满偏转时减少的百分比（‰ 的一半口径，这里直接用百分数） */
#define CHASSIS_LINE_SLOW_GAIN       50

/* 脱线保持：传感器看不到线以后，先按上一拍的差速继续走这么久再停车。
 * 20 拍确认(100 ms) + 300 ms 保持 ≈ 车再走 10~15 cm，
 * 足够让偏出去的车自己压回线上；设 0 = 立即停车（老行为）。
 * 上限受 safety：超过 800 就可能在冲出赛道后才停。 */
#define CHASSIS_LINE_LOST_HOLD_MS    300U

/* 循迹 D 项：对 position 的变化量做阻尼，抑制 S 弯里的来回摆。
 * 0    = 关闭（默认，先只跑 P，用一个变量就能打开）
 * 20~80 = 逐步加，太大（>120）会让直道也发抖
 * 单位：‰ /（position 每拍变化 1 个单位） */
#define CHASSIS_LINE_STEER_KD        30

/* 十字路口停车（2026-11-21 需求：遇到十字路口不再直行通过，直接停 + 长鸣）
 *
 * 7 路全黑持续这么久就判定为十字路口/停车线：立刻停车 + 长鸣 1 s，
 * 锁存不动，直到按 PB13 或蓝牙发 mode1/mode2 重新起跑。
 *
 * 时间怎么定：黑线横向压过时间 = 线宽 / 车速。
 *   25 mm 线 + 0.30 m/s ≈ 83 ms    → 100 能抓得住
 *   50 mm 宽停车带 + 0.30 m/s ≈ 167 ms → 同样触发
 * 调小（如 60）  ：停得更早，但线宽抖动/地面阴影可能误触发
 * 调大（如 300）：更稳，但车会冲过路口中心约 9 cm 才停
 * 设 0          ：关闭停车（只长鸣，恢复"直行通过"的老行为）
 *
 * 单位：ms */
#define CHASSIS_LINE_CROSS_MS        100U

/* ------------------------------------------------------------- 电机限制
 * 输出限幅（规范要求：所有控制输出必须限幅）。
 * ⚠️ 可调参数（MOTOR_DUTY_MAX / MOTOR_RAMP_PER_TICK）已迁到
 *    config/motor_pid_config.h，改参数请改那个文件。
 * ------------------------------------------------------------------------- */
#define CHASSIS_MOTOR_DUTY_MIN              0U

/* ------------------------------------------------------------- 跟随参数
 * 模式 2：根据「云台 yaw 偏角」转向（不是画面偏差，见 modules/vision_link.h）。
 *
 * 偏角单位统一用 0.1 度：云台行程 ±132 度 => ±1320。
 *
 * ⚠️ 跟随的转向/距离可调参数（死区、增益、目标距离、速度上限）
 *    已迁到 config/motor_pid_config.h，改参数请改那个文件。
 *    本文件只保留下面的「方向符号」和 BASE_SPEED。
 * ------------------------------------------------------------------------- */

/* 转向符号：+1 或 -1。
 * 软件层的方向修正点。差速合成已按「Motor_SetSpeed() 正值 = 后退」的
 * 硬件极性写成 left = 前后 - 转向、right = 前后 + 转向。
 *
 * 2026-11-17 实测改为 -1：修好「左右电机通道交叉」（问题记录 C-24）之后，
 * 差速输出实际作用到了正确的轮子上，转向随之整体反向 ——
 * 用户实测「云台偏角为正，车却往反方向走」，故在此取反。
 * 判据只能是「车是否朝人的方向转、偏角是否收敛」，
 * 不能靠「左右轮该谁快」的直觉（摄像头在云台上，视角与车头相反）。
 * 实测方法：架起车体，把人放到画面偏一侧，看哪边轮子变快；
 * 若转向与人的方位相反，先查差速合成，再改这里。 */
#define CHASSIS_FOLLOW_STEER_SIGN          (-1)

/* ------------------------------------------------------- 前进/后退：距离闭环
 * 距离环的可调参数（目标距离、死区、增益、速度上限、REQUIRE_DISTANCE）
 * 已迁到 config/motor_pid_config.h；这里只留调试用的定速前进值。
 * ------------------------------------------------------------------------- */

/* 兜底前进速度（千分比，负号在代码里加，这里填正数）。
 * 用于「看得到人但测不到有效距离」（超声波没回波）时慢速直行：
 *   forward_speed = -CHASSIS_FOLLOW_BASE_SPEED
 * 2026-11-16 由 250 降到 180：250 时盲走偏快，撞上去比较疼。
 * 2026-11-17 又由 180 升到 300：距离有效时最大能到 350‰，一丢距离就掉到
 *   180 会有明显「迟钝感」；现在正常情况下沿用上次速度（见
 *   CHASSIS_FOLLOW_BLIND_FORWARD_MS），只有长时间丢距离才退回本值，
 *   所以本值要够用 —— 300 与 350 只差 14%，几乎察觉不到。 */
#define CHASSIS_FOLLOW_BASE_SPEED           300U

/* ------------------------------------------------------------- 超声波
 * HC-SR04：每 60 ms 触发一次（模块要求两次测量间隔 >= 60 ms，
 * 否则上一次的余波会被当成这一次的回波，读数会突然变小）。
 * ------------------------------------------------------------------------- */

/* 触发周期，单位 ms */
#define CHASSIS_ULTRASONIC_PERIOD_MS        60U

/* 等回波超时，单位 ms。超时即判「本次无有效距离」。
 * 要小于触发周期，否则上一次还没判完就又被触发覆盖。 */
#define CHASSIS_ULTRASONIC_ECHO_TIMEOUT_MS  30U

/* 有效量程，单位 cm。超出范围按「无效」处理，不参与控制。
 * HC-SR04 标称 2~400 cm，小于 2 cm 时读数不可信。 */
#define CHASSIS_ULTRASONIC_MIN_CM           2U
#define CHASSIS_ULTRASONIC_MAX_CM           400U

/* 回波微秒 -> 厘米：cm = us / 58
 * 推导：声速 340 m/s，往返 2 倍路程 -> 1 cm 对应 58 us。
 * 温度变化会让声速变，20~30 度范围内误差约 2%，日常跟随够用。 */
#define CHASSIS_ULTRASONIC_US_PER_CM        58U

/* ------------------------------------------------- 距离滤波与保持（2026-11-14）
 * 实测 11.5 s 采样里 39% 的读数是无效的，且是成片丢（最长连续 1.8 s）。
 * 原实现在「一次没回波」的下一拍就判无效，上层立刻停车转对准，
 * 表现为「走两步停一下、还扭一下头」。下面四个参数就是治这个的。
 * ------------------------------------------------------------------------- */

/* 中值滤波窗口：最近几次「被接受的读数」取中值。
 * 5 点 = 最坏多 5×60 ms 的延迟，实际中值延迟约 2 个采样（120 ms）。
 * 调大更平、更迟钝；调到 1 等于关掉滤波。 */
#define CHASSIS_DISTANCE_MEDIAN_WINDOW      5U

/* 野值门限，单位 cm：与上一条被接受的读数相差超过这个值就当野值丢弃。
 * 40 cm / 60 ms = 6.7 m/s，人跑不了这么快，超过必是干扰或串扰。
 * 调小：更容易把真人移动误判成野值；调大：更容易把干扰放进来。 */
#define CHASSIS_DISTANCE_JUMP_CM            40U

/* 连续被门限拒绝这么多次后，认定「目标真的跳了」，强制接受一次并清空历史。
 * 防止人快速跑开时车一直抱着旧距离不放。
 * 当前值 5（= 300 ms）：实测日志里出现过 dist 201 cm 一跳到 73 cm（同一辆车、
 *   2.5 秒内），直接把 out 从 -213 翻到 +206，车猛地倒车。
 *   原因多半是转向时 15° 波束扫过了近处的桌腿/椅子，属于「几何跳变」不是「人走近」。
 *   3 次（180 ms）太容易被一次扫掠蒙过去，5 次要求持续 300 ms 才算真跳。
 * 调大：抗扫掠更强；但人真的突然跑近时反应更慢。 */
#define CHASSIS_DISTANCE_JUMP_FORCE         5U

/* 保持时间，单位 ms：丢帧期间沿用最后一次通过筛选的距离。
 * 超过这个时间仍没有新回波，才对外报「无效」，上层才切原地对准。
 * 这个值同时决定「距离无效多久开始原地对准」。
 * 调大：更不容易被打断，但用的是旧数据；调小：更灵敏，但会回到「走两步停一下」。 */
#define CHASSIS_DISTANCE_HOLD_MS            1500U

/* 新鲜判定，单位 ms：这么久内拿到过新采样才算「新鲜」（未进入保持）。
 * 只用于诊断（串口 dage）与将来降速判断，不决定跟随是否继续。 */
#define CHASSIS_DISTANCE_FRESH_MS           150U

/* 目标丢失：减速停止。
 * 实际减速由 motor_driver 的斜率限制完成（每拍最多变
 * CHASSIS_MOTOR_RAMP_PER_TICK），这里只记录期望的整车停止时间，
 * 用于文档与后续若改成显式减速曲线时的参考。 */
#define CHASSIS_FOLLOW_STOP_RAMP_MS         300U

/* ------------------------------------------------------------- 编码器
 * 每转计数（4 倍频后的总计数 / 输出轴转一圈）。
 * ⚠️ 待标定：手转输出轴一整圈，看 BSP_Encoder 累计变化量。
 * MG513 霍尔编码器常见为 11 线 × 减速比，4 倍频后 = 11 × 4 × 减速比。
 * 目前只用于显示/诊断，未参与控制；做速度闭环时才会用到。 */
#define CHASSIS_ENCODER_COUNTS_PER_REV      1320

/* ------------------------------------------------------------- 里程计（编码器航向）
 * 用两轮计数差推算车体转角、用计数和推算里程（modules/odometry.c）。
 * 阶段一**只做观测**：把 th= / od= 打到串口，不参与任何控制律。
 *
 * 标定方法（做一次就够）：
 *   1) 直线推 1.00 m，看 od= 在不在 97~103；
 *      不准 → 改 CHASSIS_WHEEL_DIAMETER_MM（新值 = 旧值 × 100 / 实测厘米数）
 *   2) 原地推着转一整圈，th= 应绕回 0 附近（中途会到 ±1800）；
 *      若转 90° 读成 80° 或 100° → 改 CHASSIS_WHEEL_TRACK_MM
 *      （新值 = 旧值 × 实读角度 / 90）
 *   3) 车头向左转时 th 应变正；若相反 → CHASSIS_ODOMETRY_HEADING_SIGN 改 -1
 */

/* 驱动轮直径（毫米）。65 mm 是按常见 MG513 轮子填的，实测为准 */
#define CHASSIS_WHEEL_DIAMETER_MM           65U

/* 两轮中心距（毫米）：量左右轮**接地点中心**之间的距离。
 * ⚠️ 这是唯一必须用尺子量的参数，量错会让所有角度等比缩放 */
#define CHASSIS_WHEEL_TRACK_MM              130U

/* 左右轮计数符号：让“两轮都前进”时位移都为正。
 * 本车实测左轮前进为正、右轮前进为负（镜像安装，见问题记录 C-04） */
#define CHASSIS_ODOMETRY_LEFT_SIGN          (+1)
#define CHASSIS_ODOMETRY_RIGHT_SIGN         (-1)

/* 航向符号：+1 时“向左转 = 正角度”。若实测相反改成 -1 */
#define CHASSIS_ODOMETRY_HEADING_SIGN       (+1)

/* ------------------------------------------------------------- 通信超时
 * 与云台板的链路超时：超过该时间没收到新数据，视为链路断开。
 * ------------------------------------------------------------------------- */
#define CHASSIS_LINK_TIMEOUT_MS             500U

#endif /* CHASSIS_CONFIG_H */
