#ifndef CHASSIS_CONFIG_H
#define CHASSIS_CONFIG_H

/* 电机/跟随的可调参数单独成册（DUTY_MAX、RAMP、FOLLOW_* 等）。
 * 在这里 include，其它 .c 文件照旧只写 #include "chassis_config.h" 即可。 */
#include "motor_pid_config.h"

/* ============================================================================
 * 循迹主控板（Chassis_2026）控制参数
 *
 * ⚠️ 本文件里的阈值全部是**占位值**，必须实测后重新标定。
 *    每个参数后面标注了标定方法，标定完把「待标定」改成实测日期。
 *
 * 对应需求：《实验室学习项目》
 *   模式 1【循迹 + 云台人体跟踪】：小车沿黑线行驶，云台独立跟踪人
 *   模式 2【纯人体跟随】：无黑线约束，整车跟随人体目标
 * ========================================================================== */

/* ------------------------------------------------------------- 任务节拍
 * 循迹需要比云台更快：红外对管响应快、黑线细，10 ms 太慢容易冲出去。
 * 5 ms（200 Hz）是常见取值。
 * ------------------------------------------------------------------------- */
#define CHASSIS_CONTROL_PERIOD_MS           5U
#define CHASSIS_CONTROL_DT_S                0.005f

#define CHASSIS_DISPLAY_PERIOD_MS           100U
#define CHASSIS_DEBUG_PERIOD_MS             500U

/* 按键消抖时间：电平稳定这么久才算一次有效动作 */
#define CHASSIS_KEY_DEBOUNCE_MS             20U

/* ------------------------------------------------------------- 循迹参数 */
/* 传感器极性：1 = 压黑线时输出低电平（多数 TCRT5000 模块）
 *           0 = 压黑线时输出高电平
 * 待标定：用万用表/OLED 看压黑线时电平。 */
#define CHASSIS_LINE_ACTIVE_LOW             1U

/* 丢线判定：连续多少次采样全部看不到黑线 -> 判为脱线 */
#define CHASSIS_LINE_LOST_COUNT             20U     /* 20 × 5 ms = 100 ms */

/* 循迹基础速度（千分比，0~1000）
 * 待标定：从 300 起，逐步加到不打滑、不脱线为止。 */
#define CHASSIS_LINE_BASE_SPEED             300U

/* 循迹转向修正强度（千分比/每单位位置偏差）
 * 待标定：先 80，赛道弯道跑不圆就加大，直线来回摆就减小。 */
#define CHASSIS_LINE_STEER_GAIN             80

/* ------------------------------------------------------------- 电机限制
 * 输出限幅（规范要求：所有控制输出必须限幅）。
 * ⚠️ 可调参数（MOTOR_DUTY_MAX / MOTOR_RAMP_PER_TICK）已迁到
 *    config/motor_pid_config.h，改参数请改那个文件。
 * ------------------------------------------------------------------------- */
#define CHASSIS_MOTOR_DUTY_MIN              0U

/* ------------------------------------------------------------- 跟随参数
 * 模式 2：根据「云台 yaw 偏角」转向（不是画面偏差，见 modules/vision_link.h）。
 *
 * 偏角单位统一用 0.1 度：云台行程 ±132 度 => ±1320。
 *
 * ⚠️ 跟随的转向/距离可调参数（死区、增益、目标距离、速度上限、
 *    REQUIRE_DISTANCE）已迁到 config/motor_pid_config.h，改参数请改那个文件。
 *    本文件只保留下面的「方向符号」和调试用的 BASE_SPEED。
 * ------------------------------------------------------------------------- */

/* 转向符号：+1 或 -1。
 * 软件层的方向修正点。差速合成已按「Motor_SetSpeed() 正值 = 后退」的
 * 硬件极性写成 left = 前后 - 转向、right = 前后 + 转向，正常保持 +1。
 * 只有确认「云台右偏 -> 车却左转」且差速合成确实无误时，才改成 -1。
 * 判据只能是「车是否朝人的方向转、偏角是否收敛」，
 * 不能靠「左右轮该谁快」的直觉（摄像头在云台上，视角与车头相反）。
 * 实测方法：架起车体，把人放到画面偏一侧，看哪边轮子变快；
 * 若转向与人的方位相反，先查差速合成，再改这里。 */
#define CHASSIS_FOLLOW_STEER_SIGN          1

/* ------------------------------------------------------- 前进/后退：距离闭环
 * 距离环的可调参数（目标距离、死区、增益、速度上限、REQUIRE_DISTANCE）
 * 已迁到 config/motor_pid_config.h；这里只留调试用的定速前进值。
 * ------------------------------------------------------------------------- */

/* 仅在 CHASSIS_FOLLOW_REQUIRE_DISTANCE = 0 时使用的定速前进值。 */
#define CHASSIS_FOLLOW_BASE_SPEED           250U

/* ------------------------------------------------------------- 超声波
 * HC-SR04：每 60 ms 触发一次（模块要求两次测量间隔 >= 60 ms，
 * 否则上一次的余波会被当成这一次的回波，读数会突然变小）。
 * ------------------------------------------------------------------------- */

/* 触发周期，单位 ms */
#define CHASSIS_ULTRASONIC_PERIOD_MS        60U

/* 等回波超时，单位 ms。超时即判「本次无有效距离」。
 * 要小于触发周期，否则上一次还没判完就又被触发覆盖。 */
#define CHASSIS_ULTRASONIC_ECHO_TIMEOUT_MS  50U

/* 有效量程，单位 cm。超出范围按「无效」处理，不参与控制。
 * HC-SR04 标称 2~400 cm，小于 2 cm 时读数不可信。 */
#define CHASSIS_ULTRASONIC_MIN_CM           2U
#define CHASSIS_ULTRASONIC_MAX_CM           400U

/* 回波微秒 -> 厘米：cm = us / 58
 * 推导：声速 340 m/s，往返 2 倍路程 -> 1 cm 对应 58 us。
 * 温度变化会让声速变，20~30 度范围内误差约 2%，日常跟随够用。 */
#define CHASSIS_ULTRASONIC_US_PER_CM        58U

/* ------------------------------------------------- 距离滤波与保持（2026-11-14）
 * 实测 11.5 s 采样里 39% 的读数是无效的，且是成片丢（最长连续 1.8 s）。
 * 原实现在「一次没回波」的下一拍就判无效，上层立刻停车转对准，
 * 表现为「走两步停一下、还扭一下头」。下面四个参数就是治这个的。
 * ------------------------------------------------------------------------- */

/* 中值滤波窗口：最近几次「被接受的读数」取中值。
 * 5 点 = 最坏多 5×60 ms 的延迟，实际中值延迟约 2 个采样（120 ms）。
 * 调大更平、更迟钝；调到 1 等于关掉滤波。 */
#define CHASSIS_DISTANCE_MEDIAN_WINDOW      5U

/* 野值门限，单位 cm：与上一条被接受的读数相差超过这个值就当野值丢弃。
 * 40 cm / 60 ms = 6.7 m/s，人跑不了这么快，超过必是干扰或串扰。
 * 调小：更容易把真人移动误判成野值；调大：更容易把干扰放进来。 */
#define CHASSIS_DISTANCE_JUMP_CM            40U

/* 连续被门限拒绝这么多次后，认定「目标真的跳了」，强制接受一次并清空历史。
 * 防止人快速跑开时车一直抱着旧距离不放。 */
#define CHASSIS_DISTANCE_JUMP_FORCE         3U

/* 保持时间，单位 ms：丢帧期间沿用最后一次通过筛选的距离。
 * 超过这个时间仍没有新回波，才对外报「无效」，上层才切原地对准。
 * 这个值同时决定「距离无效多久开始原地对准」。
 * 调大：更不容易被打断，但用的是旧数据；调小：更灵敏，但会回到「走两步停一下」。 */
#define CHASSIS_DISTANCE_HOLD_MS            1500U

/* 新鲜判定，单位 ms：这么久内拿到过新采样才算「新鲜」（未进入保持）。
 * 只用于诊断（串口 dage）与将来降速判断，不决定跟随是否继续。 */
#define CHASSIS_DISTANCE_FRESH_MS           150U

/* 目标丢失：减速停止。
 * 实际减速由 motor_driver 的斜率限制完成（每拍最多变
 * CHASSIS_MOTOR_RAMP_PER_TICK），这里只记录期望的整车停止时间，
 * 用于文档与后续若改成显式减速曲线时的参考。 */
#define CHASSIS_FOLLOW_STOP_RAMP_MS         300U

/* ------------------------------------------------------------- 编码器
 * 每转计数（4 倍频后的总计数 / 输出轴转一圈）。
 * ⚠️ 待标定：手转输出轴一整圈，看 BSP_Encoder 累计变化量。
 * MG513 霍尔编码器常见为 11 线 × 减速比，4 倍频后 = 11 × 4 × 减速比。
 * 目前只用于显示/诊断，未参与控制；做速度闭环时才会用到。 */
#define CHASSIS_ENCODER_COUNTS_PER_REV      1320

/* ------------------------------------------------------------- 通信超时
 * 与云台板的链路超时：超过该时间没收到新数据，视为链路断开。
 * ------------------------------------------------------------------------- */
#define CHASSIS_LINK_TIMEOUT_MS             500U

#endif /* CHASSIS_CONFIG_H */
