/* ------------------------------------------------------- 现象 -> 调哪个
 * （表中用简写：SPEED_MAX = CHASSIS_FOLLOW_SPEED_MAX，
 *   STEER_GAIN_Q = CHASSIS_FOLLOW_STEER_GAIN_Q，其余同理）
 *
 * 现象（实车观察）                      | 先动这个
 * --------------------------------------|------------------------------------
 * 一冲就撞过来                          | SPEED_MAX 调小
 * 追不上人                              | SPEED_MAX 调大（不超过 DUTY_MAX）
 * 车头左右摆、追着人抖                  | STEER_GAIN_Q 调小
 * 转得太肉、大角度跟不上                | STEER_GAIN_Q 调大
 * 站着不动车头也在扭                    | STEER_DEADBAND_TENTH_DEG 调大
 * 前后来回蹭（一冲一停）                | DISTANCE_DEADBAND_CM 调大
 *                                       | 或 DISTANCE_GAIN_Q 调小
 * 距离保持得松松垮垮、人走了才动        | DISTANCE_GAIN_Q 调大
 * 起步/停车太顿、电流冲击大             | RAMP_PER_TICK 调小
 * 起步太肉、跟随明显滞后                | RAMP_PER_TICK 调大
 * 跟得太近、吓人                        | TARGET_DISTANCE_CM 调大
 * 超声偶尔失效时车走走停停              | REQUIRE_DISTANCE 保持 1，先修超声
 * 搜索转太慢、一圈太久                  | SEARCH_SPIN_DUTY 调大
 * 老是在同一个方向打转                  | SEARCH_ROUNDS 调大或 SEARCH_MAX_MS 调大
 * 三轮后慢转太快/太慢                   | SEARCH_SLOW_DUTY 调小/调大
 * 看到人后停太久才恢复跟随              | SEARCH_HOLD_MS 调小
 * 人站旁边仍被一帧误检晃走              | SEARCH_HOLD_MS 调大
 * 离得太近还不退（仍在往前拱）          | SAFETY_STOP_CM 调大
 */
#endif /* __MOTOR_PID_CONFIG_H */
