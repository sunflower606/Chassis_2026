#ifndef LINE_SENSOR_H
#define LINE_SENSOR_H

/* ============================================================================
 * Module：红外黑线循迹（**7 路**）
 *
 * ⚠️ 状态：**仅搭好接口，判线算法留空**（按任务要求「循迹代码先空着」）。
 *    当前只做「把 7 路原始电平取回来」，不计算线的位置、不判断脱线。
 *
 * 需求原文（《实验室学习项目》基础要求）：
 *   「至少 5 路红外对管，能识别黑色引导线，小车沿黑线直行、转弯，不冲出赛道。」
 *   实物为 7 路，比要求多 2 路，正中多一路 CH4，转向分辨率更高。
 *
 * 实现时要补的（按顺序）：
 *   1. 极性转换：用 CHASSIS_LINE_ACTIVE_LOW 把电平转成「是否压黑线」；
 *   2. 线位置：7 路加权平均，权重 CH1..CH7 = -3 -2 -1 0 +1 +2 +3，
 *      输出 -100（最左）~ +100（最右）：
 *          position = (Σ 权重·压线通道) / (压线通道数) × (100 / 3)
 *      多路同时压线时取平均，是为了让线正好卡在两路之间时输出中间值，
 *      而不是在 -17 和 +17 之间跳。
 *   3. 脱线判定：7 路全都没压线且持续 CHASSIS_LINE_LOST_COUNT 拍；
 *   4. 标定：把每路宽度、安装间距、离地高度代入权重（间距不等时要重算权重，
 *      不能直接用 -3..+3）。
 * ========================================================================== */

#include <stdint.h>

#include "bsp_line_gpio.h"

/** @brief 循迹通道数（= 7，跟随引脚配置自动变化）。 */
#define LINE_SENSOR_CHANNEL_COUNT       BSP_LINE_CHANNEL_COUNT

/** @brief 循迹传感器快照。 */
typedef struct {
    uint8_t raw_levels;     /* 原始电平位图：bit0 = CH1 … bit6 = CH7，1 = 高电平 */
    int16_t position;       /* 线位置：-100（最左）~ +100（最右），0 = 正中。**当前恒为 0** */
    uint8_t lost;           /* 1 = 脱线。**当前恒为 1（表示「尚未实现判断」）** */
} LineSensor_t;

/* 初始化全部 7 路输入（调用 BSP 层） */
void LineSensor_Init(void);

/* 每控制周期调用一次：取一次 7 路快照 */
void LineSensor_Update(void);

/** @brief 取最近一次快照（值拷贝）。 */
LineSensor_t LineSensor_Get(void);

#endif /* LINE_SENSOR_H */
