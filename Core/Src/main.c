#include "chassis_config.h"
#include "chassis_task.h"
#include "Delay.h"

/* ============================================================================
 * 循迹主控板（Chassis_2026）入口
 *
 * 职责（与《实验室学习项目》需求对应）：
 *   模块 1【循迹 + 云台跟踪】：沿红外黑线自主行驶（云台由另一块板负责）
 *   模块 2【纯人体跟随】：根据云台板转发的人体偏差转向、保持距离
 *   模式切换按键 + OLED 显示当前模式与状态
 *
 * ⚠️ 当前阶段的代码边界：
 *   模式切换、显示、底盘外设初始化已完成；
 *   循迹判线与电机驱动的具体逻辑按任务要求**留空**（见各模块 TODO），
 *   且 Motor_SetSpeed 目前不会真正驱动电机 —— 烧进去车不会动。
 *
 * 双板分工见上级目录 ../docs/双板分工与协议.md
 * ========================================================================== */

int main(void)
{
    /* 初始化：电机（滑行）、循迹输入、按键、OLED、双板链路 */
    ChassisTask_Init();

    for (;;) {
        /* 链路轮询 -> 循迹采样 -> 按键/模式 -> 模式逻辑 -> 节流显示 */
        ChassisTask_Loop();

        /* 控制周期：必须与 CHASSIS_CONTROL_DT_S 保持一致 */
        Delay_ms(CHASSIS_CONTROL_PERIOD_MS);
    }
}
